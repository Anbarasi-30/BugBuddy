/**
 * Hint Model
 * 
 * Stores each AI-generated hint delivered to a student.
 * Linked to a specific attempt so we know the context.
 */

const mongoose = require('mongoose');

const hintSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    problemId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Problem',
      required: true,
    },
    attemptId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Attempt',
      required: true,
    },
    // The hint level this text corresponds to (1–4)
    hintLevel: {
      type: Number,
      required: true,
      min: 1,
      max: 4,
    },
    // The actual hint text generated by the AI
    hintText: {
      type: String,
      required: true,
    },
    generatedAt: {
      type: Date,
      default: Date.now,
    },
  },
  { timestamps: false }
);

module.exports = mongoose.model('Hint', hintSchema);
